#!/usr/bin/env node
// Convert a researched-providers CSV into draft SQL INSERT statements.
//
//   node scripts/csv-to-sql.mjs data/research/dewas_providers_draft.csv > draft.sql
//
// This is an alternative to the in-dashboard CSV importer. Every row is
// written with status = 'draft' and all verification flags false, so
// running the SQL never publishes anything.
import { readFileSync } from 'node:fs';
import Papa from 'papaparse';
import { missingColumns, normaliseRow } from '../src/lib/csv.js';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/csv-to-sql.mjs <file.csv> > draft.sql');
  process.exit(1);
}

const text = readFileSync(file, 'utf8').replace(/^﻿/, '');
const parsed = Papa.parse(text, {
  header: true,
  skipEmptyLines: 'greedy',
  transformHeader: (h) => h.trim().toLowerCase(),
});

const missing = missingColumns(parsed.meta.fields);
if (missing.length) {
  console.error(`Missing required column(s): ${missing.join(', ')}`);
  process.exit(1);
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

// In SQL the specialty is resolved by slug at insert time, so any slug is
// accepted here; an unknown slug simply resolves to NULL.
const anySlug = { has: () => true, get: () => null };

const COLUMNS = [
  'type', 'status', 'name', 'name_hi', 'specialty_id', 'qualifications',
  'experience_years', 'registration_number', 'registration_council',
  'clinic_name', 'address', 'area', 'city', 'state', 'pincode', 'phone',
  'maps_url', 'website_url', 'timings', 'source_url', 'source_checked_on',
  'source_notes',
];

const out = [
  '-- Sehatalaya draft provider records (generated by scripts/csv-to-sql.mjs)',
  `-- Source file: ${file}`,
  "-- All rows are inserted as status = 'draft'. Nothing is published.",
  'begin;',
];
let skipped = 0;

parsed.data.forEach((raw, i) => {
  const { record: r, errors } = normaliseRow(raw, anySlug);
  if (errors.length) {
    skipped += 1;
    console.error(`Line ${i + 2} skipped: ${errors.join('; ')}`);
    return;
  }
  const values = [
    `${q(r.type)}::public.provider_type`,
    "'draft'::public.listing_status",
    q(r.name),
    q(r.name_hi),
    r.specialty_slug
      ? `(select id from public.specialties where slug = ${q(r.specialty_slug)})`
      : 'null',
    q(r.qualifications),
    r.experience_years === null ? 'null' : String(r.experience_years),
    q(r.registration_number),
    q(r.registration_council),
    q(r.clinic_name),
    q(r.address),
    q(r.area),
    q(r.city),
    q(r.state),
    q(r.pincode),
    q(r.phone),
    q(r.maps_url),
    q(r.website_url),
    q(r.timings),
    q(r.source_url),
    r.source_checked_on ? `${q(r.source_checked_on)}::date` : 'null',
    q(r.source_notes),
  ];
  // Skip rows that already exist (same type, name and address).
  out.push(
    `insert into public.providers (${COLUMNS.join(', ')})\n` +
      `select ${values.join(', ')}\n` +
      'where not exists (\n' +
      `  select 1 from public.providers p where p.type = ${q(r.type)}::public.provider_type\n` +
      `    and lower(p.name) = lower(${q(r.name)})\n` +
      `    and lower(coalesce(p.address, '')) = lower(coalesce(${q(r.address)}, ''))\n` +
      ');',
  );
});

out.push('commit;');
console.log(out.join('\n\n'));
console.error(`Done: ${parsed.data.length - skipped} row(s) written, ${skipped} skipped.`);
